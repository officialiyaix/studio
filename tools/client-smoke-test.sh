#!/bin/bash
# tools/client-smoke-test.sh <minecraft-version>
#
# End-to-end check of the Stabled client on one Minecraft version, on Linux under Xvfb (development only):
#   1. create + install a Save through the launcher's dev tools (real Fabric stack + bundled Stabled jar)
#   2. generate a flat test world with that version's dedicated server
#   3. launch 1: intro screen -> finish with Enter x5 -> styled title screen
#   4. launch 2: quick-play into the world (motion blur on) -> HUD/FPS, pause menu, Stabled Settings, blur while turning
#
# Screenshots (intro, title, world, turning, pause, settings) and logs go to $SMOKE_DIR/<version>/.
# Requirements: Xvfb, xdotool, ImageMagick (import), python3, curl, a Mesa OpenGL driver; the client built for the
# version (client/versions/<v>/build/libs) and the launcher built with `cargo build --features dev-tools`.
# Uses an offline development profile, so singleplayer only. Environment:
#   SMOKE_DIR      output and data directory (default: ./smoke-test)
#   SMOKE_OPTIONS  extra options.txt lines, e.g. 'preferredGraphicsBackend:"vulkan"' (26.2+)
#   SMOKE_TAG      suffix for the output folder, e.g. "vulkan" -> <version>-vulkan
set -u
V=${1:?usage: client-smoke-test.sh <minecraft-version>}
REPO=$(cd "$(dirname "$0")/.." && pwd)
S=$(mkdir -p "${SMOKE_DIR:-smoke-test}" && cd "${SMOKE_DIR:-smoke-test}" && pwd)
OUT=$S/$V${SMOKE_TAG:+-$SMOKE_TAG}
DATA=$S/data
LAUNCHER=$REPO/launcher/src-tauri
export STABLED_DATA_DIR=$DATA
export DISPLAY=:99
# Minecraft 26.3 opens its window through SDL3; under Xvfb its GLX path picks a mismatched visual, EGL works.
export SDL_VIDEO_FORCE_EGL=1
mkdir -p $OUT
log() { echo "[$(date +%T)] $*" | tee -a $OUT/run.log; }

pgrep -f "Xvfb :99" >/dev/null || { Xvfb :99 -screen 0 1280x720x24 >/dev/null 2>&1 & sleep 2; }

cp $REPO/client/versions/$V/build/libs/stabled-client-1.0.0+mc$V.jar $LAUNCHER/resources/clients/stabled-client-$V.jar || exit 1

# 1. Save
if [ -f $OUT/save_id ]; then ID=$(cat $OUT/save_id); else
	# Save names must be unique, so include the tag and the time.
	ID=$($LAUNCHER/target/debug/stabled --dev create "Smoke $V${SMOKE_TAG:+ $SMOKE_TAG} $(date +%m%d-%H%M%S)" $V 2>>$OUT/run.log | tail -1)
	[[ $ID =~ ^[0-9a-f-]{36}$ ]] || { log "SAVE CREATION FAILED"; tail -3 $OUT/run.log; exit 1; }
	echo $ID > $OUT/save_id
fi
log "save $ID"
$LAUNCHER/target/debug/stabled --dev command $ID > $OUT/cmd.json 2>$OUT/install.log || { log "INSTALL FAILED"; tail -5 $OUT/install.log; exit 1; }
GAME=$(python3 -c "import json;print(json.load(open('$OUT/cmd.json'))['cwd'])")
JAVA=$(python3 -c "import json;print(json.load(open('$OUT/cmd.json'))['java'])")
SAVE_DIR=$(dirname $GAME)
log "installed; java $JAVA"

# 2. World (generated by this version's own server so no upgrade prompts appear)
if [ ! -d $GAME/saves/TestWorld ]; then
	VJSON=$DATA/shared/versions/$V/$V.json
	URL=$(python3 -c "import json;print(json.load(open('$VJSON'))['downloads']['server']['url'])")
	mkdir -p $S/servers/$V && cd $S/servers/$V
	[ -f server.jar ] || curl -sSfL -o server.jar "$URL"
	echo "eula=true" > eula.txt
	printf 'level-name=TestWorld\nlevel-type=minecraft\\:flat\ndifficulty=peaceful\nonline-mode=false\ngenerate-structures=false\nview-distance=4\nsimulation-distance=4\nspawn-protection=0\nserver-port=25%03d\n' $((RANDOM % 900 + 100)) > server.properties
	rm -rf TestWorld
	(sleep 600; echo stop) | timeout 900 $JAVA -Xmx1G -jar server.jar nogui > server.log 2>&1 &
	SP=$!
	for i in $(seq 1 300); do grep -q "Done (" server.log && break; sleep 1; done
	pkill -f "$S/servers/$V/server.jar" ; sleep 1; kill $SP 2>/dev/null
	# a clean stop is not needed: the level was saved during startup ("Preparing spawn area")
	grep -q "Done (" server.log || { log "WORLD GENERATION FAILED"; tail -5 server.log; }
	mkdir -p $GAME/saves && cp -r TestWorld $GAME/saves/TestWorld && rm -f $GAME/saves/TestWorld/session.lock
	cd $S/servers && rm -rf $V
	log "world generated"
fi

# Common launch helper: $1 = name, extra args after
launch() {
	local name=$1; shift
	python3 - "$OUT/cmd.json" "$@" > $OUT/launch-$name.sh <<'EOF'
import json, shlex, sys
c = json.load(open(sys.argv[1]))
extra = sys.argv[2:]
print("cd " + shlex.quote(c["cwd"]))
print("exec " + " ".join(shlex.quote(x) for x in [c["java"]] + c["args"] + ["--width", "1280", "--height", "720"] + extra))
EOF
	rm -f $GAME/logs/latest.log
	bash $OUT/launch-$name.sh > $OUT/game-$name.log 2>&1 &
	GPID=$!
}
shot() { import -window root $OUT/$1.png 2>/dev/null; }
wait_log() { # pattern timeout
	for i in $(seq 1 $2); do grep -qE "$1" $OUT/game-$3.log 2>/dev/null && return 0; kill -0 $GPID 2>/dev/null || return 2; sleep 1; done; return 1
}
focus() { local w; w=$(xdotool search --onlyvisible --name "Minecraft" 2>/dev/null | head -1); [ -n "$w" ] && xdotool windowfocus $w 2>/dev/null; }
stop_game() { kill $GPID 2>/dev/null; sleep 3; kill -9 $GPID 2>/dev/null; pkill -9 -f "gameDir $GAME" 2>/dev/null; sleep 1; }

# Vanilla first-run prompts off (accessibility onboarding, multiplayer warning); fixed window size
grep -q "^onboardAccessibility" $GAME/options.txt 2>/dev/null || printf 'onboardAccessibility:false\nskipMultiplayerWarning:true\njoinedFirstServer:true\ntutorialStep:none\n' >> $GAME/options.txt
# Extra options are re-applied before each launch: the first start rewrites options.txt (it has no data version yet).
apply_options() {
	[ -n "${SMOKE_OPTIONS:-}" ] || return 0
	while IFS= read -r line; do
		sed -i "/^${line%%:*}:/d" $GAME/options.txt
		echo "$line" >> $GAME/options.txt
	done <<< "$SMOKE_OPTIONS"
}

# Settings for the test: motion blur on, menus styled (defaults otherwise)
mkdir -p $SAVE_DIR/stabled
python3 - $SAVE_DIR/stabled/client.json <<'EOF'
import json, os, sys
p = sys.argv[1]
s = json.load(open(p)) if os.path.exists(p) else {}
s.setdefault("motionBlur", {}).update({"enabled": True, "strength": 70})
json.dump(s, open(p, "w"), indent=2)
EOF

# 3. Launch 1: intro and title
rm -f $SAVE_DIR/stabled/onboarding.json
apply_options
launch menu
log "launch 1 (menus)"
wait_log "Stabled Client ready" 240 menu || log "no ready line"
sleep 25; focus; shot intro
for i in 1 2 3 4 5; do focus; xdotool key Return; sleep 2; [ $i = 2 ] && shot intro2; done
sleep 3; shot title
stop_game
grep -q '"completed": *true' $SAVE_DIR/stabled/onboarding.json 2>/dev/null && log "intro completed via Finish" || log "INTRO NOT COMPLETED"

# 4. Launch 2: world
apply_options
launch world --quickPlaySingleplayer TestWorld
log "launch 2 (world)"
wait_log "joined the game|Loaded [0-9]+ advancements|logged in with entity" 300 world
sleep 30; focus; shot world
# turn the camera while capturing: motion blur trails should be visible
focus; for i in $(seq 1 12); do xdotool mousemove_relative --sync 40 0 2>/dev/null; sleep 0.05; done; shot turning
sleep 2; focus; xdotool key Escape; sleep 3; shot pause
focus; xdotool key Escape; sleep 2; focus; xdotool key Shift_R; sleep 3; shot settings
stop_game

# 5. Result
cp $GAME/logs/latest.log $OUT/latest-world.log 2>/dev/null
ERR=$(grep -hE "Mixin apply|InvalidInjectionException|InjectionError|MixinTransformerError|Exception in|Stabled: motion blur disabled|Crash report|NoSuchMethodError|NoSuchFieldError|AbstractMethodError" $OUT/game-*.log | head -5)
[ -n "$ERR" ] && { log "ERRORS:"; echo "$ERR" | tee -a $OUT/run.log; } || log "no errors in logs"
log "done"
