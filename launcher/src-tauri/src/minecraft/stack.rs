//! Supported Minecraft versions and the pinned Stabled stack for each (stack/<version>.json).
//! Only combinations listed here are offered for new Saves; everything else is shown as unsupported.

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::sync::OnceLock;

pub const PRIMARY_VERSION: &str = "26.3";

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StackMod {
    pub mod_id: String,
    pub title: String,
    pub purpose: String,
    pub required: bool,
    pub project: String,
    pub version_id: String,
    pub version_number: String,
    pub version_type: String,
    pub filename: String,
    pub url: String,
    pub sha512: String,
    pub size: u64,
    pub license: Option<String>,
    /// A library another mod of a game mode needs (shown with that mod in the UI).
    #[serde(default)]
    pub library: bool,
    /// Game-mode mods that need this library.
    #[serde(default)]
    pub needed_by: Vec<String>,
}

/// A game mode's mods for one Minecraft version.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct ModeStack {
    #[serde(default)]
    pub mods: Vec<StackMod>,
    /// Why a mod of the mode isn't available for this version.
    #[serde(default)]
    pub notes: Vec<String>,
}

/// A game mode: a named set of extra mods a Save can switch to (e.g. CPVP).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GameModeInfo {
    pub id: String,
    pub name: String,
    pub description: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Loader {
    pub id: String,
    pub version: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct JavaSpec {
    pub component: String,
    pub major_version: u32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Stack {
    pub minecraft: String,
    pub revision: u32,
    pub loader: Loader,
    pub java: JavaSpec,
    pub mods: Vec<StackMod>,
    /// Why a usual component is missing for this version (e.g. no compatible build exists).
    #[serde(default)]
    pub notes: Vec<String>,
    /// Extra mods per game mode id (generated by tools/update_game_modes.py).
    #[serde(default)]
    pub modes: BTreeMap<String, ModeStack>,
}

impl Stack {
    pub fn key(&self) -> String {
        format!("{}@{}", self.minecraft, self.revision)
    }

    pub fn fabric_profile_id(&self) -> String {
        format!("fabric-loader-{}-{}", self.loader.version, self.minecraft)
    }
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct StacksFile {
    stacks: Vec<Stack>,
    #[serde(default)]
    game_modes: Vec<GameModeInfo>,
    #[serde(default)]
    default_game_mode: String,
}

static FILE: OnceLock<StacksFile> = OnceLock::new();

fn file() -> &'static StacksFile {
    FILE.get_or_init(|| serde_json::from_str::<StacksFile>(include_str!("../../stack/stacks.json")).expect("stack/stacks.json"))
}

/// Every supported version, oldest first (generated and verified by tools/update_stacks.py).
pub fn all() -> &'static Vec<Stack> {
    &file().stacks
}

/// The game modes a Save can use (generated by tools/update_game_modes.py).
pub fn game_modes() -> &'static [GameModeInfo] {
    &file().game_modes
}

/// The game mode new Saves start in (CPVP).
pub fn default_game_mode() -> &'static str {
    let d = file().default_game_mode.as_str();
    if game_modes().iter().any(|m| m.id == d) {
        d
    } else {
        game_modes().first().map(|m| m.id.as_str()).unwrap_or("standard")
    }
}

pub fn is_game_mode(id: &str) -> bool {
    game_modes().iter().any(|m| m.id == id)
}

/// A game mode's extra mods for a stack (empty for an unknown mode or a mode without mods).
pub fn mode_stack(stack: &Stack, mode: &str) -> ModeStack {
    stack.modes.get(mode).cloned().unwrap_or_default()
}

pub fn for_version(version: &str) -> Option<&'static Stack> {
    all().iter().find(|s| s.minecraft == version)
}

pub fn is_supported(version: &str) -> bool {
    for_version(version).is_some()
}

/// Mod id of the bundled Stabled client. It is required for every Save and protected from removal.
pub const STABLED_MOD_ID: &str = "stabled";
/// File name of the Stabled client inside a Save's mods folder.
pub const STABLED_JAR_NAME: &str = "stabled-client.jar";

/// File name of the bundled Stabled client build for a Minecraft version (resources/clients/).
pub fn bundled_jar_name(minecraft: &str) -> String {
    format!("stabled-client-{minecraft}.jar")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn game_modes_are_complete() {
        assert_eq!(default_game_mode(), "cpvp");
        assert!(is_game_mode("standard"));
        for st in all() {
            for g in game_modes() {
                let m = mode_stack(st, &g.id);
                for x in &m.mods {
                    assert_eq!(x.sha512.len(), 128, "{} {}", st.minecraft, x.title);
                    assert!(x.url.starts_with("https://cdn.modrinth.com/"), "{}", x.url);
                    // Never a second copy of a mod the Stabled stack already installs.
                    assert!(!st.mods.iter().any(|s| s.mod_id == x.mod_id), "{} duplicates {}", st.minecraft, x.mod_id);
                }
                // Every library is needed by a mod of the mode.
                for lib in m.mods.iter().filter(|x| x.library) {
                    assert!(lib.needed_by.iter().all(|n| m.mods.iter().any(|x| !x.library && &x.title == n)));
                }
            }
        }
        // 1.21.11 uses the exact CPVP builds chosen for it.
        let cpvp = mode_stack(for_version("1.21.11").unwrap(), "cpvp");
        let files: Vec<&str> = cpvp.mods.iter().filter(|m| !m.library).map(|m| m.filename.as_str()).collect();
        assert_eq!(
            files,
            ["TierTagger-2.4.3+mc1.21.11.jar", "ShieldStatus-4.2.1+1.21.11.jar", "ShieldFixes-2.1.0+1.21.11.jar", "totemtweaks-1.21.11-1.1.0.jar", "IAS-9.0.8+1.21.11-fabric.jar"]
        );
    }
}
